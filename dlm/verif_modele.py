# FULL VERIFICATION — RUN EVERYTHING
# ═══════════════════════════════════════════════════════════════════════════════

def run_full_validation(
    y: np.ndarray,
    dates: pd.DatetimeIndex,
    sigma_trend: float,
    sigma_seas: float,
    sigma_obs: float,
    sigma_ar: float = 0.0,
    rho: float = RHO,
    trend_dec: float = 0.0,
    mcmc_result: dict | None = None,
    proxies: np.ndarray | None = None,
    beta: np.ndarray | None = None,
) -> dict:
    """
    Runs the 5 verification levels and produces a summary report.
    """
    print("\n" + "="*60)
    print(" FULL VERIFICATION OF THE DLM + AR(1) MODEL -- OZONE")
    print("="*60)

    kf = kalman_filter(y, sigma_obs, sigma_trend, sigma_seas,
                       sigma_ar, proxies, beta, rho=rho)

    results = {}

    results["innov"] = check_innovations(kf, dates=dates)

    results["mcmc"] = check_mcmc_convergence(y, proxies=proxies, beta=beta)

    results["synth"] = test_synthetic_recovery(
        n=min(len(y), 450),
        true_sigma_trend=sigma_trend,
        true_sigma_seas=sigma_seas,
        true_sigma_obs=sigma_obs,
        true_sigma_ar=sigma_ar,
        true_rho=rho,
        true_trend_dec=trend_dec,
    )

    results["loyo"] = leave_one_year_out(y, sigma_trend, sigma_seas,
                                         sigma_obs, dates,
                                         sigma_ar=sigma_ar, rho=rho)

    results["comp"] = compare_dlm_mlr(y, sigma_trend, sigma_seas,
                                      sigma_obs, sigma_ar,
                                      proxies, beta, rho=rho,
                                      mcmc_result=mcmc_result)

    print("\n" + "="*60)
    print(" FINAL SUMMARY")
    print("="*60)
    checks = [
        ("White-noise innovations", results["innov"]["ok"]),
        ("MCMC convergence (Rhat/ESS)", results["mcmc"]["ok"]),
        ("Parameter recovery", results["synth"]["inside_params"]
         and results["synth"]["inside_trend"]),
        ("Leave-one-out coverage",
         results["loyo"]["total_coverage"] >= 0.80),
    ]
    for name, ok in checks:
        print(f" {'OK' if ok else 'FAIL'} {name}")

    print(f"\n -> Figures in {OUTPUT_DIR}/")
    return results


