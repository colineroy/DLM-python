# RIGOROUS MCMC DIAGNOSTICS (rank-normalized split-Rhat + Geyer ESS)
# ═══════════════════════════════════════════════════════════════════════════════

def _rank_normalize(x: np.ndarray) -> np.ndarray:
    """Rank -> normal transform (Vehtari et al. 2021), robust to heavy
    tails -- used for the split-Rhat instead of the raw values."""
    ranks = stats.rankdata(x, method="average")
    n = len(x)
    return stats.norm.ppf((ranks - 3/8) / (n - 1/4 + 1))


def _split_rhat(chains_list: list) -> float:
    """
    Rank-normalized split-Rhat (Vehtari et al. 2021, bulk-only version).
    Each chain is cut into 2 halves, treated as additional independent
    chains: detects both a lack of convergence between chains AND
    non-stationarity within a chain.
    """
    split = []
    for c in chains_list:
        n = len(c)
        h = n // 2
        split.append(c[:h])
        split.append(c[h:2*h])
    n = len(split[0])
    m = len(split)
    pooled = np.concatenate(split)
    z_pooled = _rank_normalize(pooled)
    z_split = [z_pooled[i*n:(i+1)*n] for i in range(m)]
    means = np.array([s.mean() for s in z_split])
    B = n * np.var(means, ddof=1)
    W = np.mean([np.var(s, ddof=1) for s in z_split])
    if W <= 0:
        return np.nan
    var_hat = (n - 1) / n * W + B / n
    return float(np.sqrt(var_hat / W))


def _autocorr_1d(x: np.ndarray, max_lag: int) -> np.ndarray:
    x = x - x.mean()
    n = len(x)
    var = np.dot(x, x) / n
    if var <= 0:
        return np.zeros(max_lag + 1)
    return np.array([np.dot(x[:n-lag], x[lag:]) / n / var
                     for lag in range(max_lag + 1)])


def _geyer_ess(chains_list: list) -> float:
    """
    ESS via Geyer's (1992) initial positive sequence, averaged over
    several chains -- replaces the crude AR(1) approximation.
    """
    n = len(chains_list[0])
    m = len(chains_list)
    max_lag = min(n - 2, 500)
    acfs = np.array([_autocorr_1d(c, max_lag) for c in chains_list])
    acf_mean = acfs.mean(axis=0)

    tau = 1.0
    t = 1
    while t < max_lag - 1:
        pair = acf_mean[t] + acf_mean[t + 1]
        if pair < 0:
            break
        tau += 2 * pair
        t += 2
    tau = max(tau, 1e-6)
    return max((n * m) / tau, 1.0)


