"""
=============================================================================
DLM model verification — 5 diagnostic levels
=============================================================================

Ozone version, ported from DLM/dlmpython_ch4/verif_modele.py with the
fixes introduced during the critical review of the CH4 methodology:

Level 1: Innovation v(t) diagnostics
-> The filter residuals must be Gaussian white noise.
-> SEASONAL heteroscedasticity test (Levene by calendar month, not a
  simple chronological first-half/second-half variance ratio); Ljung-Box
  reduced to 2 lags (1, 12) with Bonferroni correction instead of 4
  uncorrected tests (otherwise P(reject wrongly >=1 time) ~18% even
  under white noise).

Level 2: MCMC convergence
-> Audit with 4 independent chains, dispersed starting points: a proper
  R-hat (rank-normalized split-Rhat, Vehtari et al. 2021) and ESS via
  Geyer's (1992) initial positive sequence, instead of a single chain
  with a crude AR(1) approximation that can detect neither a hidden
  mode nor poor autocorrelation decay.

Level 3: Synthetic-data test
-> y(t) is generated by direct simulation of the full state-space model
  (G, F, Q) with KNOWN parameters, the pipeline is run, and we check
  that the injected values are recovered.

Level 4: Leave-one-year-out (cross-validation)
-> One year of data is removed, predicted with the model (forward
  filter, no information leakage from the future), and compared to the
  true value.

Level 5: DLM vs MLR comparison
-> DIC (Spiegelhalter et al. 2002), not the naive AIC with k=hyperparameters
  alone, which undercounts the effective degrees of freedom of a model
  with a smoothed stochastic trend. R^2 is kept for information only
  (the DLM structurally nests the MLR, so R^2_DLM >= R^2_MLR is nearly
  guaranteed by construction and proves nothing). The MLR's AIC includes
  the full Gaussian constant (n*(1+ln 2pi)) to stay on the same scale as
  the Kalman filter's likelihood -- omitting it would systematically
  bias the comparison in favor of the MLR.
=============================================================================
"""

