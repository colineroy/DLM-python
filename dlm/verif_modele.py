# LEVEL 4 — LEAVE-ONE-YEAR-OUT
# ═══════════════════════════════════════════════════════════════════════════════

def leave_one_year_out(
    y: np.ndarray,
    sigma_trend: float,
    sigma_seas: float,
    sigma_obs: float,
    dates: pd.DatetimeIndex = None,
    n_years_test: int = 5,
    sigma_ar: float = 0.0,
    rho: float = RHO,
) -> dict:
    """
    LEVEL 4: Leave-one-year-out cross-validation.
    """
    n = len(y)
    years = dates.year.unique()
    step = max(1, len(years) // (n_years_test + 1))
    test_years = sorted(years[step::step][:n_years_test])

    print(f"\n{'='*60}")
    print(f" LEVEL 4 — LEAVE-ONE-YEAR-OUT ({n_years_test} years)")
    print(f"{'='*60}")
    print(f" Test years: {list(test_years)}")

    results = []
    all_coverage = []

    for yr in test_years:
        y_masked = y.copy()
        mask_idx = np.where(dates.year == yr)[0]
        y_true = y[mask_idx].copy()
        y_masked[mask_idx] = np.nan

        kf_masked = kalman_filter(y_masked, sigma_obs, sigma_trend,
                                  sigma_seas, sigma_ar, rho=rho)

        F = make_F()
        preds = []
        for i in mask_idx:
            pred_mean = (F @ kf_masked["x_pred"][i])[0]
            pred_var = (F @ kf_masked["P_pred"][i] @ F.T)[0, 0] + sigma_obs**2
            preds.append({"mean": pred_mean, "std": np.sqrt(pred_var)})

        coverage = []
        for j, (i, p) in enumerate(zip(mask_idx, preds)):
            if not np.isnan(y_true[j]):
                in_ic = abs(y_true[j] - p["mean"]) < 1.96 * p["std"]
                coverage.append(in_ic)

        rate = np.mean(coverage) if coverage else np.nan
        all_coverage.extend(coverage)
        rmse = np.sqrt(np.nanmean(
            (y_true - np.array([p["mean"] for p in preds]))**2))
        results.append({"year": yr, "coverage": rate, "rmse": rmse})
        print(f" {yr} : CI95 coverage = {rate:.0%} "
              f"RMSE = {rmse:.4f} "
              f"({'OK' if rate >= 0.80 else 'WARNING'})")

    total_coverage = np.mean(all_coverage)
    print(f"\n Overall coverage: {total_coverage:.1%} "
          f"(expected ~ 95% — "
          f"{'OK' if 0.80 <= total_coverage <= 1.0 else 'WARNING'})")

    return {"results": results, "total_coverage": total_coverage}


