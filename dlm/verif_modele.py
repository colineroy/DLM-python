# LEVEL 1 — INNOVATION DIAGNOSTICS
# ═══════════════════════════════════════════════════════════════════════════════

def check_innovations(kf_result: dict,
                      dates: pd.DatetimeIndex | None = None,
                      title: str = "Innovation diagnostics") -> dict:
    """
    LEVEL 1: Checks that the innovations v(t) are Gaussian white noise.

    dates : index of the observations, used to group the
        heteroscedasticity test by calendar month (Test 4) rather than
        a simple chronological split into 2 halves, which cannot detect
        seasonal heteroscedasticity (e.g. sonde/FTIR retrieval noise
        stronger in the polar winter).
    """
    v = kf_result["v"]
    S = kf_result["S"]
    mask = ~np.isnan(v) & ~np.isnan(S) & (S > 0)
    if dates is not None:
        dates = dates[mask]
    v = v[mask]
    S = S[mask]
    v_std = v / np.sqrt(S)
    n = len(v)

    print(f"\n{'='*60}")
    print(f" LEVEL 1 — INNOVATION DIAGNOSTICS: {title}")
    print(f"{'='*60}")

    # ── Test 1: zero mean ─────────────────────────────────────────────
    t_stat, p_mean = stats.ttest_1samp(v_std, 0)
    ok_mean = p_mean > 0.05
    print(f"\n Test 1 — Zero mean (t-test):")
    print(f" Mean = {v_std.mean():.4f} (should be ~ 0)")
    print(f" p = {p_mean:.4f} -> {'OK' if ok_mean else 'PROBLEM'}")

    # ── Test 2: normality (Shapiro-Wilk on a subsample) ────────────
    sample = v_std[:min(n, 500)]
    _, p_norm = shapiro(sample)
    ok_norm = p_norm > 0.05
    print(f"\n Test 2 — Normality (Shapiro-Wilk):")
    print(f" p = {p_norm:.4f} -> {'OK' if ok_norm else 'WARNING'}")

    # ── Test 3: autocorrelation (Ljung-Box, lags 1 and 12, Bonferroni) ────
    from statsmodels.stats.diagnostic import acorr_ljungbox
    alpha_corr = 0.05 / 2
    lb = acorr_ljungbox(v_std, lags=[1, 12], return_df=True)
    p_lb = lb["lb_pvalue"].values
    ok_lb = np.all(p_lb > alpha_corr)
    print(f"\n Test 3 — Autocorrelation (Ljung-Box, Bonferroni threshold {alpha_corr:.3f}):")
    for lag, p in zip([1, 12], p_lb):
        flag = "OK" if p > alpha_corr else "AUTOCORRELATION"
        print(f" lag={lag:2d} p={p:.4f} -> {flag}")
    print(f" Conclusion: {'OK' if ok_lb else 'AUTOCORR'}")

    # ── Test 4: SEASONAL heteroscedasticity (Levene, 12 months) ─────────
    if dates is not None:
        months = dates.month.values
        groups = [v_std[months == m] for m in range(1, 13)]
        groups = [g for g in groups if len(g) >= 3]
        if len(groups) >= 2:
            _, p_het = stats.levene(*groups, center="median")
            ok_het = p_het > 0.05
            print(f"\n Test 4 — Seasonal homoscedasticity (Levene, {len(groups)} months):")
            print(f" p = {p_het:.4f} -> {'OK' if ok_het else 'HETEROSCEDASTICITY'}")
        else:
            ok_het, p_het = True, np.nan
            print(f"\n Test 4 — Homoscedasticity: not enough distinct months, skipped")
    else:
        mid = len(v_std) // 2
        var1 = np.var(v_std[:mid])
        var2 = np.var(v_std[mid:])
        ratio = max(var1, var2) / min(var1, var2)
        ok_het = ratio < 2.0
        p_het = np.nan
        print(f"\n Test 4 — Homoscedasticity (fallback, no dates):")
        print(f" 1st/2nd-half ratio = {ratio:.2f} -> {'OK' if ok_het else 'HETEROSCEDASTICITY'}")

    # ── Summary ─────────────────────────────────────────────────────────────
    all_ok = ok_mean and ok_norm and ok_lb and ok_het
    print(f"\n SUMMARY: {'Model well specified' if all_ok else 'Check the model'}")
    if not ok_lb:
        print(" -> Suggestion: increase sigma_trend or add an AR term")
    if not ok_norm:
        print(" -> Suggestion: check for outliers in the data")

    # ── Figure ─────────────────────────────────────────────────────────────
    fig = plt.figure(figsize=(14, 10))
    _setup_dark(fig)
    gs = gridspec.GridSpec(2, 2, figure=fig, hspace=0.4, wspace=0.35)
    t_idx = np.arange(n)

    ax1 = fig.add_subplot(gs[0, :])
    ax1.plot(t_idx, v_std, lw=0.8, color=C["blue"], alpha=0.7)
    ax1.axhline(0, color="#888", lw=0.8)
    ax1.axhline(2, color=C["amber"], lw=0.8, ls="--", alpha=0.6)
    ax1.axhline(-2, color=C["amber"], lw=0.8, ls="--", alpha=0.6,
                label="+/-2 sigma (95% expected)")
    pct_out = 100 * np.mean(np.abs(v_std) > 2)
    ax1.set_title(
        f"Standardized innovations v(t)/sqrt(S(t)) — {pct_out:.1f}% > 2 sigma "
        f"(expected 5%)",
        fontsize=11, color=C["text"])
    ax1.set_ylabel("v/sqrt(S)", fontsize=10)
    ax1.legend(fontsize=8.5, framealpha=0.3)
    ax1.grid(color=C["grid"], lw=0.6)

    ax2 = fig.add_subplot(gs[1, 0])
    x_ref = np.linspace(-4, 4, 200)
    ax2.hist(v_std, bins=30, density=True, color=C["blue"], alpha=0.6,
             label="Observed innovations")
    ax2.plot(x_ref, stats.norm.pdf(x_ref), color=C["red"], lw=2,
             label="Theoretical N(0,1)")
    ax2.set_title(f"Distribution (Shapiro p={p_norm:.3f})",
                  fontsize=10, color=C["text"])
    ax2.legend(fontsize=8.5, framealpha=0.3)
    ax2.grid(color=C["grid"], lw=0.6)

    ax3 = fig.add_subplot(gs[1, 1])
    stats.probplot(v_std, dist="norm", plot=ax3)
    ax3.get_lines()[0].set(color=C["blue"], alpha=0.6, markersize=3)
    ax3.get_lines()[1].set(color=C["red"], lw=2)
    ax3.set_title("Q-Q plot (should be a straight line)", fontsize=10,
                  color=C["text"])
    ax3.grid(color=C["grid"], lw=0.6)

    plt.savefig(OUTPUT_DIR / "verif1_innovations.png",
                dpi=150, bbox_inches="tight", facecolor=fig.get_facecolor())
    plt.close()
    print(f"\n -> Figure: {OUTPUT_DIR}/verif1_innovations.png")

    return {"ok": all_ok, "p_mean": p_mean, "p_norm": p_norm,
            "p_lb": p_lb, "p_het": p_het}


# ═══════════════════════════════════════════════════════════════════════════════
# LEVEL 2 — MCMC CONVERGENCE (multi-chain audit)
# ═══════════════════════════════════════════════════════════════════════════════

def check_mcmc_convergence(
    y: np.ndarray,
    prior: dict | None = None,
    n_chains: int = 4,
    n_iter: int = 3000,
    n_burnin: int = 1000,
    proxies: np.ndarray | None = None,
    beta: np.ndarray | None = None,
) -> dict:
    """
    LEVEL 2: Convergence audit using 4 independent MCMC chains with
    dispersed starting points. Rhat (rank-normalized split-Rhat) + Geyer
    ESS, instead of a single chain with an AR(1) approximation.
    """
    if prior is None:
        prior = make_prior(y)

    print(f"\n{'='*60}")
    print(f" LEVEL 2 — MCMC CONVERGENCE ({n_chains} chains, audit)")
    print(f"{'='*60}")

    mc = run_mcmc_multichain(y, prior, n_chains=n_chains, n_iter=n_iter,
                             n_burnin=n_burnin, proxies=proxies, beta=beta)
    chains_list = mc["chains_list"]
    d = chains_list[0].shape[1]
    all_names = ["log sigma_trend", "log sigma_seas", "log sigma_obs", "log sigma_ar", "logit rho"]
    names = all_names[:d]
    n = chains_list[0].shape[0]

    print(f" {n_chains} chains x {n} post-burn-in samples")
    print(f" Mean acceptance rate: {mc['accept_rate']:.1%} "
          f"({'OK' if 0.10 < mc['accept_rate'] < 0.50 else 'WARNING'})")

    fig, axes = plt.subplots(d, 3, figsize=(14, 3.3 * d), squeeze=False)
    fig.suptitle(f"MCMC diagnostics ({n_chains} chains)", fontsize=13)
    _setup_dark(fig)

    rhat_list, ess_list = [], []
    chain_colors = [C["blue"], C["red"], C["green"], C["amber"], C["purp"]]
    for i, name in enumerate(names):
        per_chain = [chains_list[c][:, i] for c in range(n_chains)]
        pooled = np.concatenate(per_chain)
        param_pooled = _sigmoid(pooled) if name == "logit rho" else np.exp(pooled)

        ax = axes[i, 0]
        for c in range(n_chains):
            ax.plot(per_chain[c], lw=0.5,
                    color=chain_colors[c % len(chain_colors)], alpha=0.7)
        ax.set_title(f"Trace ({n_chains} chains) — {name}", fontsize=9, color=C["text"])
        ax.set_xlabel("Iteration", fontsize=8)
        ax.grid(color=C["grid"], lw=0.4)

        ax = axes[i, 1]
        max_lag = min(100, n // 4)
        acf_mean = _autocorr_1d(per_chain[0], max_lag)
        lags = np.arange(0, max_lag + 1)
        ax.bar(lags, acf_mean, color=C["blue"], alpha=0.6, width=0.8)
        ax.axhline(1.96/np.sqrt(n), color=C["amber"], ls="--", lw=1)
        ax.axhline(-1.96/np.sqrt(n), color=C["amber"], ls="--", lw=1)
        ax.set_title(f"Autocorrelation — {name}", fontsize=9, color=C["text"])
        ax.set_xlabel("Lag", fontsize=8)
        ax.grid(color=C["grid"], lw=0.4)

        ax = axes[i, 2]
        ax.hist(param_pooled, bins=40, density=True, color=C["green"], alpha=0.6)
        med = np.median(param_pooled)
        lo, hi = np.percentile(param_pooled, [2.5, 97.5])
        ax.axvline(med, color=C["red"], lw=1.5, label=f"Median={med:.5f}")
        ax.axvspan(lo, hi, alpha=0.15, color=C["red"],
                   label=f"CI95=[{lo:.5f},{hi:.5f}]")
        ax.set_title(f"Posterior — {name}", fontsize=9, color=C["text"])
        ax.legend(fontsize=7, framealpha=0.3)
        ax.grid(color=C["grid"], lw=0.4)

        rhat = _split_rhat(per_chain)
        ess = _geyer_ess(per_chain)
        rhat_list.append(rhat)
        ess_list.append(ess)
        ok_rhat = rhat < 1.01
        ok_ess = ess > 400
        print(f"\n {name}:")
        print(f" Median = {med:.6f} CI95=[{lo:.6f}, {hi:.6f}]")
        print(f" Rhat = {rhat:.4f} -> {'OK' if ok_rhat else 'NOT CONVERGED (Rhat > 1.01)'}")
        print(f" ESS (Geyer) = {ess:.0f} -> {'OK' if ok_ess else 'ESS too low'}")

    plt.tight_layout()
    plt.savefig(OUTPUT_DIR / "verif2_mcmc.png",
                dpi=150, bbox_inches="tight", facecolor=fig.get_facecolor())
    plt.close()
    print(f"\n -> Figure: {OUTPUT_DIR}/verif2_mcmc.png")

    all_ok = all(r < 1.01 for r in rhat_list) and all(e > 400 for e in ess_list)
    print(f"\n LEVEL 2 SUMMARY: {'Multi-chain convergence confirmed' if all_ok else 'Convergence doubtful'}")

    return {"rhat": rhat_list, "ess": ess_list, "ok": all_ok, "names": names}


# ═══════════════════════════════════════════════════════════════════════════════
# LEVEL 3 — SYNTHETIC-DATA TEST (the most fundamental)
# ═══════════════════════════════════════════════════════════════════════════════

def test_synthetic_recovery(
    n: int = 450,
    true_sigma_trend: float = 0.0003,
    true_sigma_seas: float = 0.008,
    true_sigma_obs: float = 0.04,
    true_sigma_ar: float = 0.0,
    true_rho: float = RHO,
    true_trend_dec: float = 1.5,   # %/dec
    n_mcmc: int = 3000,
    seed: int = 42,
) -> dict:
    """
    LEVEL 3: Recovery test on synthetic data (5 parameters, including the
    AR(1) state). Generated by direct simulation of the state-space model
    (G, F, Q): guarantees that the synthetic data are exactly consistent
    with the model fitted by MCMC.
    """
    np.random.seed(seed)
    print(f"\n{'='*60}")
    print(f" LEVEL 3 — SYNTHETIC-DATA TEST")
    print(f"{'='*60}")
    print(f"\n Injected parameters:")
    print(f" sigma_trend = {true_sigma_trend:.5f}")
    print(f" sigma_seas = {true_sigma_seas:.4f}")
    print(f" sigma_obs = {true_sigma_obs:.4f}")
    print(f" sigma_ar = {true_sigma_ar:.5f}")
    print(f" rho = {true_rho:.4f}")
    print(f" trend = {true_trend_dec:+.2f} %/dec")

    t_mo = np.arange(n, dtype=float)

    G = make_G(true_rho)
    F = make_F()[0]
    Q = make_Q(true_sigma_trend, true_sigma_seas, true_sigma_ar)

    x = np.zeros(N_STATE)
    x[1] = true_trend_dec / 100 / 120
    for k in range(len(FREQS)):
        x[2 + 2*k] = 0.12 if k == 0 else 0.04

    states = np.zeros((n, N_STATE))
    for i in range(n):
        if i > 0:
            w = np.random.multivariate_normal(np.zeros(N_STATE), Q)
            x = G @ x + w
        states[i] = x

    harm_idx = [2 + 2*k for k in range(len(FREQS))]
    true_signal = states[:, 0] + states[:, harm_idx].sum(axis=1)

    # Trend REALIZED by the simulated random walk, distinct from the
    # INITIAL slope injected (true_trend_dec): over a window of n
    # months, even a modest sigma_trend accumulates a drift with std
    # sigma_trend*sqrt(n)*12000 (%/dec) that can far exceed the initial
    # slope -- comparing the MCMC estimate to the initial slope rather
    # than to the actually realized mean trend would produce a false
    # failure (the random walk, not the pipeline, would have "drifted").
    t_true = np.arange(n, dtype=float)
    A_true = np.column_stack([np.ones(n), t_true])
    c_true, *_ = np.linalg.lstsq(A_true, states[:, 0], rcond=None)
    true_trend_realized = c_true[1] * 120 * 100

    obs_noise = np.random.normal(0, true_sigma_obs, n)
    y = states @ F + obs_noise

    missing = np.random.choice(n, size=int(0.05*n), replace=False)
    y[missing] = np.nan

    print(f"\n Series generated: {n} months, {len(missing)} NaN "
          f"({len(missing)/n:.0%})")

    kf_true = kalman_filter(y, true_sigma_obs, true_sigma_trend,
                            true_sigma_seas, true_sigma_ar, rho=true_rho)
    ks_true = kalman_smoother(kf_true, rho=true_rho)

    prior = make_prior(y)
    mcmc_r = run_mcmc(y, prior, n_iter=n_mcmc, n_burnin=1000,
                      verbose=False)

    print(f"\n MCMC results:")
    all_inside = True
    for name, true_val, samp in [
        ("sigma_trend", true_sigma_trend, mcmc_r["sigma_trend"]),
        ("sigma_seas", true_sigma_seas, mcmc_r["sigma_seas"]),
        ("sigma_obs", true_sigma_obs, mcmc_r["sigma_obs"]),
        ("sigma_ar", true_sigma_ar, mcmc_r["sigma_ar"]),
        ("rho", true_rho, mcmc_r["rho"]),
    ]:
        lo, hi = np.percentile(samp, [2.5, 97.5])
        inside = lo <= true_val <= hi
        if not inside:
            all_inside = False
        print(f" {name:<12} : true={true_val:.5f} "
              f"CI95=[{lo:.5f},{hi:.5f}] "
              f"{'INSIDE CI' if inside else 'OUTSIDE CI'}")

    sigma_t = np.median(mcmc_r["sigma_trend"])
    sigma_s = np.median(mcmc_r["sigma_seas"])
    sigma_o = np.median(mcmc_r["sigma_obs"])
    sigma_a = np.median(mcmc_r["sigma_ar"])
    rho_est = np.median(mcmc_r["rho"])
    kf_est = kalman_filter(y, sigma_o, sigma_t, sigma_s, sigma_a, rho=rho_est)
    ks_est = kalman_smoother(kf_est, rho=rho_est)
    sim_est = simulation_smoother(ks_est, n_samples=200)

    t_arr = np.arange(n, dtype=float)
    trends = []
    for k in range(sim_est["level_samp"].shape[0]):
        mu = sim_est["level_samp"][k]
        valid = ~np.isnan(mu)
        if valid.sum() > 10:
            A = np.column_stack([np.ones(valid.sum()), t_arr[valid]])
            c, *_ = np.linalg.lstsq(A, mu[valid], rcond=None)
            trends.append(c[1]*120*100)
    trends = np.array(trends)
    trend_est = np.median(trends)
    lo_t, hi_t = np.percentile(trends, [2.5, 97.5])
    inside_t = lo_t <= true_trend_realized <= hi_t

    print(f"\n trend: injected (initial slope)={true_trend_dec:+.2f} %/dec "
          f"realized (random walk)={true_trend_realized:+.2f} %/dec")
    print(f" trend: true={true_trend_realized:+.2f} %/dec "
          f"estimated={trend_est:+.2f} "
          f"CI95=[{lo_t:+.2f},{hi_t:+.2f}] "
          f"{'INSIDE CI' if inside_t else 'OUTSIDE CI'}")

    print(f"\n SUMMARY: "
          f"{'Pipeline correct' if all_inside and inside_t else 'Problem detected'}")

