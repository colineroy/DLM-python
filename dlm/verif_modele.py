# LEVEL 5 — DLM vs MLR COMPARISON
# ═══════════════════════════════════════════════════════════════════════════════

def compare_dlm_mlr(
    y: np.ndarray,
    sigma_trend: float,
    sigma_seas: float,
    sigma_obs: float,
    sigma_ar: float = 0.0,
    proxies: np.ndarray | None = None,
    beta: np.ndarray | None = None,
    rho: float = RHO,
    mcmc_result: dict | None = None,
) -> dict:
    """
    LEVEL 5: Compares the DLM with a simple linear MLR.

    DIC (lower = better) if mcmc_result is provided, otherwise naive AIC.
    R^2 -- INFORMATIVE ONLY, not a decision criterion.
    """
    n = len(y)
    print(f"\n{'='*60}")
    print(f" LEVEL 5 — DLM vs MLR COMPARISON")
    print(f"{'='*60}")

    valid = ~np.isnan(y)
    y_v = y[valid]
    t_v = np.arange(n)[valid].astype(float)

    omega1, omega2 = 2*np.pi/12, 2*np.pi/6
    X_mlr = [np.ones(valid.sum()), t_v,
             np.cos(omega1*t_v), np.sin(omega1*t_v),
             np.cos(omega2*t_v), np.sin(omega2*t_v)]
    if proxies is not None and beta is not None:
        for p in range(proxies.shape[1]):
            X_mlr.append(proxies[valid, p])
    A_mlr = np.column_stack(X_mlr)
    coef_mlr, *_ = np.linalg.lstsq(A_mlr, y_v, rcond=None)
    y_hat_mlr = A_mlr @ coef_mlr
    resid_mlr = y_v - y_hat_mlr
    ss_res_mlr = np.sum(resid_mlr**2)
    ss_tot = np.sum((y_v - y_v.mean())**2)
    r2_mlr = 1 - ss_res_mlr / ss_tot
    k_mlr = A_mlr.shape[1]
    n_v = valid.sum()
    # Full AIC (Gaussian constant included) -- comparable to the Kalman
    # filter's likelihood, which includes it explicitly.
    aic_mlr = n_v * np.log(ss_res_mlr/n_v) + n_v * (1 + np.log(2*np.pi)) + 2*k_mlr
    trend_mlr_dec = coef_mlr[1] * 120 * 100

    kf_dlm = kalman_filter(y, sigma_obs, sigma_trend, sigma_seas,
                           sigma_ar, proxies, beta, rho=rho)
    ks_dlm = kalman_smoother(kf_dlm, rho=rho)

    obs_idx = np.nonzero(make_F()[0])[0]
    y_hat_dlm = sum(ks_dlm["x_smooth"][:, idx][valid]
                    for idx in obs_idx)
    if proxies is not None and beta is not None:
        y_hat_dlm += proxies[valid] @ beta
    resid_dlm = y_v - y_hat_dlm
    ss_res_dlm = np.sum(resid_dlm**2)
    r2_dlm = 1 - ss_res_dlm / ss_tot

    k_dlm_naive = 5
    aic_dlm_naive = -2 * kf_dlm["loglik"] + 2 * k_dlm_naive

    dic_dlm = None
    p_d = None
    if mcmc_result is not None:
        chains = mcmc_result["chains"]
        n_draws = len(chains)
        thin = max(1, n_draws // 500)
        idx = np.arange(0, n_draws, thin)
        st_i = np.exp(chains[idx, 0])
        ss_i = np.exp(chains[idx, 1])
        so_i = np.exp(chains[idx, 2])
        sa_i = np.exp(chains[idx, 3])
        rh_i = _sigmoid(chains[idx, 4])
        logliks = np.array([
            kalman_filter(y, so_i[j], st_i[j], ss_i[j], sa_i[j], proxies, beta,
                         rho=rh_i[j])["loglik"]
            for j in range(len(idx))
        ])
        D_bar = -2 * np.mean(logliks)

        theta_bar_t = chains.mean(axis=0)
        ll_bar = kalman_filter(
            y, np.exp(theta_bar_t[2]), np.exp(theta_bar_t[0]),
            np.exp(theta_bar_t[1]), np.exp(theta_bar_t[3]), proxies, beta,
            rho=_sigmoid(theta_bar_t[4]))["loglik"]
        D_theta_bar = -2 * ll_bar
        p_d = D_bar - D_theta_bar
        dic_dlm = D_bar + p_d
        if p_d < 0:
            print(f"\n (p_D={p_d:.2f} < 0: a known DIC pathology when the "
                  f"posterior is very tight -- not an error in itself, "
                  f"but indicates high sensitivity to the chosen "
                  f"theta_bar point; interpret with caution)")

    print(f"\n {'Metric':<24} {'MLR':>10} {'DLM':>10}")
    print(f" {'-'*46}")
    print(f" {'Naive AIC (k=5)':<24} {'—':>10} {aic_dlm_naive:>10.1f}")
    if dic_dlm is not None:
        print(f" {'DIC (p_D={:.1f})'.format(p_d):<24} {aic_mlr:>10.1f} {dic_dlm:>10.1f} "
              f"{'  DLM better' if dic_dlm < aic_mlr else '  MLR better'}")
    else:
        print(f" {'AIC':<24} {aic_mlr:>10.1f} {aic_dlm_naive:>10.1f} "
              f"{'  DLM better' if aic_dlm_naive < aic_mlr else '  MLR better'}")
    print(f" {'R2 (informative only)':<24} {r2_mlr:>10.4f} {r2_dlm:>10.4f}")
    print(f" {'Trend %/dec':<24} {trend_mlr_dec:>+10.2f} {'(variable)':>10}")

    aic_dlm = dic_dlm if dic_dlm is not None else aic_dlm_naive
    delta_aic = aic_mlr - aic_dlm
    crit_name = "Delta DIC" if dic_dlm is not None else "Delta AIC (naive)"
    if delta_aic > 10:
        print(f"\n {crit_name} = {delta_aic:.1f}: DLM clearly better -> non-linear trend")
    elif delta_aic > 2:
        print(f"\n {crit_name} = {delta_aic:.1f}: DLM slightly better")
    elif delta_aic > -2:
        print(f"\n {crit_name} = {delta_aic:.1f}: DLM and MLR equivalent -> near-linear trend")
    elif delta_aic > -10:
        print(f"\n {crit_name} = {delta_aic:.1f}: MLR slightly better")
    else:
        print(f"\n {crit_name} = {delta_aic:.1f}: MLR clearly better -> the DLM brings "
              f"no net gain once the effective degrees of freedom are counted")

    fig, axes = plt.subplots(1, 2, figsize=(13, 5))
    _setup_dark(fig)
    fig.suptitle("Level 5 — DLM vs MLR", fontsize=12, color=C["text"])

    axes[0].plot(np.arange(valid.sum()), resid_mlr,
                 lw=0.7, color=C["amber"], alpha=0.7, label="MLR residuals")
    axes[0].plot(np.arange(valid.sum()), resid_dlm,
                 lw=0.7, color=C["green"], alpha=0.7, label="DLM residuals")
    axes[0].axhline(0, color="#888", lw=0.8)
    axes[0].set_title(
        f"Residuals | MLR AIC={aic_mlr:.0f} DLM AIC/DIC={aic_dlm:.0f}",
        fontsize=10, color=C["text"])
    axes[0].legend(fontsize=8.5, framealpha=0.3)
    axes[0].grid(color=C["grid"], lw=0.6)

    axes[1].bar(["MLR", "DLM"], [r2_mlr, r2_dlm],
                color=[C["amber"], C["green"]], alpha=0.7, width=0.5)
    axes[1].set_title(f"R2 (informative) | MLR={r2_mlr:.4f} DLM={r2_dlm:.4f}",
                      fontsize=10, color=C["text"])
    axes[1].set_ylabel("R2", fontsize=10)
    axes[1].set_ylim(0, max(r2_mlr, r2_dlm) * 1.3)
    axes[1].grid(axis="y", color=C["grid"], lw=0.6)

    plt.tight_layout()
    plt.savefig(OUTPUT_DIR / "verif5_dlm_vs_mlr.png",
                dpi=150, bbox_inches="tight", facecolor=fig.get_facecolor())
    plt.close()
    print(f"\n -> Figure: {OUTPUT_DIR}/verif5_dlm_vs_mlr.png")

    return {"aic_mlr": aic_mlr, "aic_dlm": aic_dlm,
            "aic_dlm_naive": aic_dlm_naive, "dic_dlm": dic_dlm, "p_d": p_d,
            "r2_mlr": r2_mlr, "r2_dlm": r2_dlm,
            "delta_aic": delta_aic}


